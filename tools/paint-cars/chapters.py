#!/usr/bin/env python3
"""Writes games/garage-evolution/painted/index.ts: every painted picture with its asset chapter (game_platform D84,
docs/guides/art.md § 5.2). Chapter 0 loads before Play: the Shed's cars (a new player's first garage). The later garages
come in the order a player reaches them, a tier at a time. Chapter 0 is only the first car (always the Glide): the Shed's
other cars lead chapter 1, in by ≈ 3 s after Play, long before a new player's second car (≈ 20 s). 1 the rest of the
Shed, the Corner Garage, the Tuning Workshop and Rally Works;
2 the Service Station, the Muscle Shop and the GT Atelier; 3 the luxury tier; 4 the plant tier. Run it after
paint_cars.py (a new picture) or after a car moves garage: python3 tools/paint-cars/chapters.py"""
import pathlib
import re
import json

ROOT = pathlib.Path(__file__).resolve().parents[2]
GAME = ROOT / 'games' / 'garage-evolution'
PAINTED = GAME / 'painted'
CHAPTER_OF_SITE = {
    'shed': 1,
    'corner': 1, 'tuning': 1, 'rally': 1,
    'station': 2, 'muscle': 2, 'gt': 2,
    'luxury': 3, 'racing': 3, 'prestige': 3,
    'plant': 4, 'hyper': 4, 'future': 4,
}

data = (GAME / 'data.ts').read_text()
chapter_of_model = {}
for site, pool in re.findall(r"\{ id: '([a-z]+)', tier: \d.*?pool: \[([^\]]*)\]", data):
    for m in re.findall(r"'([a-z0-9]+)'", pool):
        chapter_of_model[m] = CHAPTER_OF_SITE.get(site, 4)
chapter_of_model['aero'] = 0

native_meta = json.loads((PAINTED / 'meta.json').read_text())
active_cars = {name for name, art in native_meta.items() if art['img']['w'] >= 900}
files = sorted(p.name for p in PAINTED.glob('*.webp') if p.name.split('-')[0] in active_cars)
lines = [
    '// Generated by tools/paint-cars/chapters.py: do not edit (run it again). Every painted picture and its asset chapter:',
    '// 0 loads before Play (the Shed), the later garages after it, a tier at a time (docs: art.md § 5.2).',
    '',
]
urls, chapters = [], []
for f in files:
    name = f[:-len('.webp')]
    model = name.split('-')[0]
    ch = chapter_of_model.get(model, 4)
    var = 'p_' + re.sub(r'[^a-z0-9]', '_', name)
    q = '?url' if ch == 0 else f'?gp-chapter={ch}'
    lines.append(f"import {var} from './{f}{q}';")
    urls.append(f"  '{name}': {var},")
    if ch:
        chapters.append(f"  '{name}': {ch},")
lines += ['', '/** Picture name (`<model>`, `<model>-w0`, `<model>-bf` …) → its URL */', 'export const URLS: Record<string, string> = {', *urls, '};',
          '', '/** Picture name → its chapter (missing: 0, before Play) */', 'export const CHAPTERS: Record<string, number> = {', *chapters, '};', '']
(PAINTED / 'index.ts').write_text('\n'.join(lines))
by = {}
for f in files:
    by.setdefault(chapter_of_model.get(f[:-5].split('-')[0], 4), []).append(f)
print(' · '.join(f'chapter {c}: {len(v)} pictures, {sum((PAINTED / x).stat().st_size for x in v) // 1024} KB' for c, v in sorted(by.items())))
